"""Plate / personal-data masking for anything sent to Groq.

The assistant may restyle an aggregate into a sentence, and that sentence is
generated by a third party. A plate number is the one field in this product that
identifies a person's vehicle, so it is replaced with a stable placeholder
(``VEH_1``, ``VEH_2``) before the request leaves the process, and the real values
are substituted back into the model's reply afterwards.

Two properties matter:

* Deterministic - the same plate always maps to the same placeholder, so the
  model cannot be confused by the same car appearing as VEH_1 in one sentence
  and VEH_2 in the next.
* Reversible only by us - :func:`unmask` only ever substitutes values that came
  from the mapping we built, so a placeholder the model invented resolves to
  nothing and is dropped by the phrasing guard.
"""

from __future__ import annotations

import re
from typing import Iterable

PLACEHOLDER_PREFIX = "VEH_"

# A candidate plate as it can appear inside free text. Deliberately loose: the
# masker runs over data we already know is a plate, so a false positive costs a
# placeholder, while a false negative would leak a real plate. The guard in
# router.py re-checks the phrased output with the stricter plate validator.
_PLATE_LIKE = re.compile(r"\b[A-Z]{2}[\s-]?\d{1,2}[\s-]?[A-Z]{0,3}[\s-]?\d{1,4}\b", re.IGNORECASE)

# Placeholders as they may come back from the model, e.g. "VEH_1" or "VEH 1".
_PLACEHOLDER_LIKE = re.compile(r"\bVEH[\s_-]?(\d{1,2})\b", re.IGNORECASE)


def _unique_in_order(values: Iterable[str]) -> list[str]:
    """Deduplicate while keeping first-seen order.

    ``set()`` would do the same job but drop order, and order is what makes the
    numbering deterministic: VEH_1 must always be the plate that appears first.
    """
    seen: set[str] = set()
    ordered: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            ordered.append(value)
    return ordered


class Masker:
    """Builds and applies one plate -> placeholder mapping."""

    def __init__(self) -> None:
        self._to_placeholder: dict[str, str] = {}
        self._to_value: dict[str, str] = {}

    def _placeholder_for(self, value: str) -> str:
        existing = self._to_placeholder.get(value)
        if existing:
            return existing
        placeholder = f"{PLACEHOLDER_PREFIX}{len(self._to_placeholder) + 1}"
        self._to_placeholder[value] = placeholder
        self._to_value[placeholder] = value
        return placeholder

    def mask_text(self, text: str, extra_values: Iterable[str] = ()) -> str:
        """Replace any known plate (plus explicit ``extra_values``) with a placeholder."""
        out = text
        # Longest first so a plate that contains another as a prefix does not
        # get torn apart ("MH12JK4567" before "MH12JK4").
        known = sorted(set(self._to_placeholder) | {v for v in extra_values if v}, key=len, reverse=True)
        for value in known:
            if value and value in out:
                out = out.replace(value, self._placeholder_for(value))
        for found in _unique_in_order(_PLATE_LIKE.findall(out)):
            out = out.replace(found, self._placeholder_for(found))
        return out

    def mask_value(self, value: str) -> str:
        return self._placeholder_for(value)

    def unmask(self, text: str) -> str:
        """Put real plates back. Unknown placeholders are left untouched."""

        def _sub(match: re.Match[str]) -> str:
            key = f"{PLACEHOLDER_PREFIX}{match.group(1)}"
            return self._to_value.get(key, match.group(0))

        return _PLACEHOLDER_LIKE.sub(_sub, text)

    @property
    def mapping(self) -> dict[str, str]:
        return dict(self._to_value)

    def placeholders(self) -> set[str]:
        return set(self._to_value)

    def real_values(self) -> set[str]:
        return set(self._to_placeholder)
