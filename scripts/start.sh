wait_readiness() {
  local backend_ok=0 citizen_ok=0 police_ok=0 expo_ok=0 pg_ok=0 redis_ok_final=0

  step "waiting for the backend (60s)"
  if wait_http "http://127.0.0.1:$PORT_BACKEND/api/v1/healthz" 60 || wait_http "http://127.0.0.1:$PORT_BACKEND/health" 5; then
    backend_ok=1; ok "Backend API"; else err "Backend API  (logs/backend.err.log)"; fi
  record_result "Backend API" "$backend_ok" "http://${LAN_IP}:8000/docs"

  if wait_http "http://127.0.0.1:$PORT_CITIZEN/" 30; then citizen_ok=1; ok "Citizen web"; else err "Citizen web  (logs/citizen.err.log)"; fi
  record_result "Citizen web" "$citizen_ok" "http://${LAN_IP}:5173"

  if wait_http "http://127.0.0.1:$PORT_POLICE/" 30; then police_ok=1; ok "Police dashboard"; else err "Police dashboard  (logs/police.err.log)"; fi
  record_result "Police dashboard" "$police_ok" "http://${LAN_IP}:5174"

  if [ "$NO_MOBILE" -eq 0 ]; then
    if wait_http "http://127.0.0.1:$PORT_EXPO/status" 45; then expo_ok=1; ok "Expo Metro (mobile)"; else err "Expo Metro  (logs/expo.err.log)"; fi
  fi
  record_result "Expo Metro" "$expo_ok" "http://${LAN_IP}:8081"

  if redis_ok; then redis_ok_final=1; ok "Redis"; else err "Redis"; fi
  record_result "Redis" "$redis_ok_final" "localhost:6379"

  if postgres_ok; then pg_ok=1; ok "PostgreSQL"; else err "PostgreSQL"; fi
  record_result "PostgreSQL" "$pg_ok" "localhost:5432"

  [ "$backend_ok" -eq 1 ] || return 1
  return 0
}

