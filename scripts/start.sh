# --------------------------------------------------------------------------- #
# Reset
# --------------------------------------------------------------------------- #
do_reset() {
  warn "This stops every service AND deletes the demo data."
  if [ "$EFFECTIVE_MODE" = "docker" ]; then
    warn "  docker volumes (postgres data) will be wiped"
  else
    warn "  the PostgreSQL database '${POSTGRES_DB:-rakshak}' will be dropped and recreated"
  fi
  confirm "Are you sure?" n || { info "reset cancelled"; return; }

  step "stopping everything"
  "$SCRIPT_DIR/stop.sh" --mode "$EFFECTIVE_MODE" >/dev/null 2>&1 || true

  if [ "$EFFECTIVE_MODE" = "docker" ]; then
    step "removing containers and volumes"
    ( cd "$REPO_ROOT" && docker compose down -v >/dev/null 2>&1 ) || warn "docker compose down -v failed"
    ok "docker volumes removed"
    rm -f "$SEED_MARKER"
    return
  fi

  local psql user pass db
  if psql_cmd >/dev/null; then
    psql="$(psql_cmd)"
    user="${POSTGRES_USER:-postgres}"; pass="${POSTGRES_PASSWORD:-postgres}"; db="${POSTGRES_DB:-rakshak}"
    step "dropping database '$db'"
    PGPASSWORD="$pass" "$psql" -h localhost -U "$user" -d postgres -tAc "DROP DATABASE IF EXISTS $db WITH (FORCE)" >/dev/null 2>&1 || true
    PGPASSWORD="$pass" "$psql" -h localhost -U "$user" -d postgres -tAc "CREATE DATABASE $db" >/dev/null 2>&1 || warn "could not recreate '$db'"
    ok "database '$db' dropped and recreated"
  else
    warn "psql not found - drop the database manually: DROP DATABASE ${POSTGRES_DB:-rakshak} WITH (FORCE); CREATE DATABASE ${POSTGRES_DB:-rakshak};"
  fi

  for name in backend citizen police expo; do stop_tracked "$name"; done
  for port in "$PORT_BACKEND" "$PORT_CITIZEN" "$PORT_POLICE" "$PORT_EXPO"; do
    pid="$(port_pid "$port" | tr -d '[:space:]')"
    [ -n "$pid" ] && kill_tree "$pid"
  done
  for name in backend citizen police expo; do stop_tracked "$name"; done
  for port in "$PORT_BACKEND" "$PORT_CITIZEN" "$PORT_POLICE" "$PORT_EXPO"; do
    pid="$(port_pid "$port" | tr -d '[:space:]')"
    [ -n "$pid" ] && kill_tree "$pid"
  done
  rm -f "$SEED_MARKER"
  ok "reset finished - the services will start again in a moment"
}

