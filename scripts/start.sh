npm_deps() { # dir, key, install (yes/no)
  local dir="$1" key="$2" install="$3"
  local current prev
  current="$(hash_of "$dir/package-lock.json")$(hash_of "$dir/package.json")"
  prev="$(hash_recorded "$key")"
  local leaf; leaf="$(basename "$dir")"

  if [ "$install" = "no" ]; then
    if [ "$REBUILD" -eq 1 ] || [ "$current" != "$prev" ] || [ ! -d "$dir/node_modules" ]; then
      step "$leaf: installing node dependencies"
      ( cd "$dir" && npm ci --no-audit --no-fund >"$LOG_DIR/npm-$leaf.log" 2>&1 ) \
        || die "npm ci failed in $dir - see logs/npm-$leaf.log"
      ok "$leaf: node dependencies installed"
    else
      info "$leaf: dependencies unchanged - skipping npm ci"
    fi
    record_hash "$key" "$current"
    return
  fi
  if [ -d "$dir/node_modules" ] && [ "$current" = "$prev" ] && [ "$REBUILD" -eq 0 ]; then
    info "$leaf: dependencies unchanged - skipping npm ci"
    record_hash "$key" "$current"
    return
  fi
  info "$leaf: dependencies need installing (skipped)"
}

