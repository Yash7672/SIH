init_local_database() {
  if ! psql_cmd >/dev/null; then
    warn "psql not found - skipping the create-database-if-missing check"
    return
  fi
  local psql user pass db
  psql="$(psql_cmd)"
  user="${POSTGRES_USER:-postgres}"
  pass="${POSTGRES_PASSWORD:-postgres}"
  db="${POSTGRES_DB:-rakshak}"

  if PGPASSWORD="$pass" "$psql" -h localhost -U "$user" -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname='$db'" 2>/dev/null | grep -q 1; then
    ok "database '$db' exists"
    return
  fi
  step "creating database '$db'"
  if PGPASSWORD="$pass" "$psql" -h localhost -U "$user" -d postgres -tAc "CREATE DATABASE $db" >/dev/null 2>&1; then
    ok "database '$db' created"
  else
    warn "could not create '$db' (it may already exist)"
  fi
}

hash_recorded() { # key
  [ -f "$HASHES_PATH" ] || return 1
  grep -q "\"$1\":" "$HASHES_PATH" || return 1
  json_get "$HASHES_PATH" "$1" | tr -d '" '
}

record_hash() { # key, value
  mkdir -p "$STATE_DIR"
  local key="$1" value="$2"
  if [ -f "$HASHES_PATH" ]; then
    if grep -q "\"$key\":" "$HASHES_PATH"; then
      sed -i.bak -E "s|\"$key\":[[:space:]]*\"[^\"]*\"|\"$key\": \"$value\"|" "$HASHES_PATH" && rm -f "$HASHES_PATH.bak"
      return
    fi
  fi
  printf '  "%s": "%s"\n}\n' "$key" "$value" >> "$STATE_DIR/hashes.tmp" 2>/dev/null || true
  if [ -f "$STATE_DIR/hashes.tmp" ]; then
    { echo "{"; cat "$STATE_DIR/hashes.tmp"; } > "$HASHES_PATH"
    rm -f "$STATE_DIR/hashes.tmp"
  fi
}

init_python_venv() {
  local python
  python="$(python_cmd)"
  [ "$REBUILD" -eq 1 ] && { warn "-Rebuild: recreating .venv"; rm -rf "$VENV_DIR"; }

  if [ ! -d "$VENV_DIR" ]; then
    step "creating virtual environment at $VENV_DIR"
    "$python" -m venv "$VENV_DIR" || die "could not create the virtual environment at $VENV_DIR"
    ok "virtual environment created"
  fi

  local vpython="$VENV_DIR/bin/python"
  [ -x "$vpython" ] || die "the virtual environment at $VENV_DIR is broken - delete it and re-run"

  local alembic="$VENV_DIR/bin/alembic"
  [ -x "$alembic" ] || die "alembic is not installed in $VENV_DIR - re-run with --rebuild"

  local req_hash prev
  req_hash="$(hash_of "$BACKEND_DIR/requirements.txt")"
  prev="$(hash_recorded backend-requirements)"

  if [ "$REBUILD" -eq 1 ] || [ "$req_hash" != "$prev" ]; then
    step "installing backend dependencies (requirements.txt changed)"
    "$vpython" -m pip install --disable-pip-version-check -q -r "$BACKEND_DIR/requirements.txt" \
      || die "pip install failed - run it by hand in $VENV_DIR to see the error"
    ok "backend dependencies installed"
  else
    info "backend dependencies unchanged - skipping pip install"
  fi
  record_hash backend-requirements "$req_hash"
}

